// Concatenates supabase/migrations/*.sql (all idempotent) into supabase/setup.sql — one file to
// paste into the Supabase SQL Editor, safe to run on a fresh or partially migrated database.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../supabase/migrations/", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const body = files
  .map((f) => `-- ════════════════ ${f} ════════════════\n${readFileSync(new URL(f, dir), "utf8").trim()}\n`)
  .join("\n");
writeFileSync(
  new URL("../supabase/setup.sql", import.meta.url),
  `-- GENERATED by scripts/build-setup-sql.mjs — do not edit by hand.\n-- Paste this whole file into Supabase → SQL Editor → Run. Safe to re-run.\n\n${body}`,
);
console.log(`supabase/setup.sql ← ${files.join(", ")}`);
